/**
 * Una etapa del selector de pruebas (modo admin, F2).
 *
 * Las etapas de una misión son ACUMULATIVAS: al saltar a la etapa N se aplican en orden los cambios de
 * todas las anteriores (flags, ítems, ropa) sobre una partida nueva de esa misión. Cada etapa declara
 * solo lo que pasó desde la anterior. Para agregar una, basta sumarla en su lugar de la lista.
 *
 * Las flags `enter_<mapa>_<id>` marcan como ya vista una escena de llegada. Si una etapa NO la marca,
 * la escena corre al aparecer (a propósito: suele ser justo lo que se quiere probar).
 */
export interface AdminStage {
  label: string;
  map: string;
  spawn: string;
  /** Hora de la historia: "vie 12:45". */
  clock?: string;
  /** Tope del reloj; sin tope, el reloj queda detenido en `clock`. */
  max?: string;
  weather?: Weather;
  objective?: string;
  flags?: string[];
  clear?: string[];
  items?: string[];
  take?: string[];
  outfit?: Partial<Outfit>;
  /** Saldo que se carga en la Bip! */
  bip?: number;
  /** Solo en la etapa de destino: script (o "dialogo:<id>") que parte apenas aparece el jugador. */
  run?: string;
}

